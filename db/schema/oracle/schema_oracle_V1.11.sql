-- 1. users : 회원
CREATE TABLE users (
  user_id      NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
  email        VARCHAR2(255 CHAR) NOT NULL,
  password     VARCHAR2(255 CHAR),
  name         VARCHAR2(50 CHAR)  NOT NULL,
  nickname     VARCHAR2(30 CHAR)  NOT NULL,
  phone        VARCHAR2(20 CHAR),
  role         VARCHAR2(20 CHAR)  DEFAULT 'USER' NOT NULL,
  created_at   TIMESTAMP(0)       DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at   TIMESTAMP(0)       DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_users          PRIMARY KEY (user_id),
  CONSTRAINT uk_users_email    UNIQUE (email),
  CONSTRAINT uk_users_nickname UNIQUE (nickname),
  CONSTRAINT ck_users_role     CHECK (role IN ('USER', 'ADMIN'))
);

-- 2. user_agreements : 약관 동의 이력
CREATE TABLE user_agreements (
  agreement_id    NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
  user_id         NUMBER(19)      NOT NULL,
  agreement_type  VARCHAR2(30 CHAR) NOT NULL,
  is_agreed       NUMBER(1)       DEFAULT 1 NOT NULL,
  agreed_at       TIMESTAMP(0)    DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_user_agreements                PRIMARY KEY (agreement_id),
  CONSTRAINT ck_user_agreements_agreement_type CHECK (agreement_type IN ('TERMS', 'PRIVACY', 'LOCATION', 'MARKETING')),
  CONSTRAINT ck_user_agreements_is_agreed      CHECK (is_agreed IN (0, 1))
);

-- 3. social_accounts : 소셜 계정 연동
CREATE TABLE social_accounts (
  social_account_id  NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
  user_id            NUMBER(19)       NOT NULL,
  provider           VARCHAR2(20 CHAR)  NOT NULL,
  provider_user_id   VARCHAR2(100 CHAR) NOT NULL,
  connected_at       TIMESTAMP(0)     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_social_accounts          PRIMARY KEY (social_account_id),
  CONSTRAINT uk_social_provider          UNIQUE (provider, provider_user_id),
  CONSTRAINT ck_social_accounts_provider CHECK (provider IN ('KAKAO', 'NAVER'))
);

-- 4. auth_tokens : 인증 토큰
CREATE TABLE auth_tokens (
  token_id       NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
  user_id        NUMBER(19)       NOT NULL,
  refresh_token  VARCHAR2(512 CHAR) NOT NULL,
  issued_at      TIMESTAMP(0)     DEFAULT SYSTIMESTAMP NOT NULL,
  expires_at     TIMESTAMP(0)     NOT NULL,
  revoked_at     TIMESTAMP(0),
  user_agent     VARCHAR2(255 CHAR),
  CONSTRAINT pk_auth_tokens  PRIMARY KEY (token_id),
  CONSTRAINT uk_auth_refresh UNIQUE (refresh_token)
);

-- 5. email_verifications : 이메일 인증
CREATE TABLE email_verifications (
  verification_id  NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
  user_id          NUMBER(19),
  email            VARCHAR2(255 CHAR) NOT NULL,
  purpose          VARCHAR2(20 CHAR)  NOT NULL,
  code_hash        VARCHAR2(255 CHAR) NOT NULL,
  expires_at       TIMESTAMP(0)     NOT NULL,
  attempt_count    NUMBER(10)       DEFAULT 0 NOT NULL,
  verified_at      TIMESTAMP(0),
  created_at       TIMESTAMP(0)     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_email_verifications         PRIMARY KEY (verification_id),
  CONSTRAINT ck_email_verifications_purpose CHECK (purpose IN ('WITHDRAWAL', 'SIGNUP', 'PASSWORD_RESET'))
);

-- 6. subway_lines : 지하철 노선
CREATE TABLE subway_lines (
  line_id        NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
  line_name      VARCHAR2(50 CHAR) NOT NULL,
  line_number    VARCHAR2(10 CHAR),
  display_order  NUMBER(10)      DEFAULT 0 NOT NULL,
  CONSTRAINT pk_subway_lines      PRIMARY KEY (line_id),
  CONSTRAINT uk_subway_lines_name UNIQUE (line_name)
);

-- 7. stations : 지하철 역
CREATE TABLE stations (
  station_id    NUMBER(19)        GENERATED BY DEFAULT AS IDENTITY,
  station_name  VARCHAR2(100 CHAR) NOT NULL,
  latitude      NUMBER(10,7)      NOT NULL,
  longitude     NUMBER(10,7)      NOT NULL,
  address       VARCHAR2(255 CHAR),
  CONSTRAINT pk_stations PRIMARY KEY (station_id)
);

-- 8. line_stations : 노선-역 매핑
CREATE TABLE line_stations (
  line_station_id  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
  line_id          NUMBER(19) NOT NULL,
  station_id       NUMBER(19) NOT NULL,
  station_order    NUMBER(10) NOT NULL,
  CONSTRAINT pk_line_stations               PRIMARY KEY (line_station_id),
  CONSTRAINT uk_line_stations               UNIQUE (line_id, station_id),
  CONSTRAINT ck_line_stations_station_order CHECK (station_order >= 1)
);

-- 9. train_timetables : 열차 시간표
CREATE TABLE train_timetables (
  timetable_id            NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
  train_no                VARCHAR2(20 CHAR),
  line_id                 NUMBER(19)      NOT NULL,
  station_id              NUMBER(19)      NOT NULL,
  day_type                VARCHAR2(10 CHAR) NOT NULL,
  direction               VARCHAR2(10 CHAR) NOT NULL,
  arrival_time            VARCHAR2(8 CHAR),
  departure_time          VARCHAR2(8 CHAR),
  destination_station_id  NUMBER(19),
  CONSTRAINT pk_train_timetables           PRIMARY KEY (timetable_id),
  CONSTRAINT ck_train_timetables_day_type  CHECK (day_type  IN ('WEEKDAY', 'WEEKEND')),
  CONSTRAINT ck_train_timetables_direction CHECK (direction IN ('UP', 'DOWN')),
  CONSTRAINT ck_train_timetables_time      CHECK (arrival_time IS NOT NULL OR departure_time IS NOT NULL),
  CONSTRAINT ck_tt_arrival_format          CHECK (arrival_time   IS NULL OR REGEXP_LIKE(arrival_time,   '^[0-9]{2}:[0-9]{2}:[0-9]{2}$')),
  CONSTRAINT ck_tt_departure_format        CHECK (departure_time IS NULL OR REGEXP_LIKE(departure_time, '^[0-9]{2}:[0-9]{2}:[0-9]{2}$'))
);

-- 10. places : 추천 장소
CREATE TABLE places (
  place_id     NUMBER(19)        GENERATED BY DEFAULT AS IDENTITY,
  place_name   VARCHAR2(100 CHAR) NOT NULL,
  category     VARCHAR2(30 CHAR)  NOT NULL,
  description  CLOB,
  address      VARCHAR2(255 CHAR) NOT NULL,
  latitude     NUMBER(10,7)      NOT NULL,
  longitude    NUMBER(10,7)      NOT NULL,
  phone        VARCHAR2(20 CHAR),
  created_by   NUMBER(19),
  created_at   TIMESTAMP(0)      DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at   TIMESTAMP(0)      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_places          PRIMARY KEY (place_id),
  CONSTRAINT ck_places_category CHECK (category IN ('TOUR', 'RESTAURANT', 'CAFE', 'SHOPPING', 'ETC'))
);

-- 11. place_stations : 장소-역 매핑
CREATE TABLE place_stations (
  place_station_id  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
  place_id          NUMBER(19) NOT NULL,
  station_id        NUMBER(19) NOT NULL,
  CONSTRAINT pk_place_stations PRIMARY KEY (place_station_id)
);

-- 12. place_images : 장소 이미지
CREATE TABLE place_images (
  place_image_id  NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
  place_id        NUMBER(19)       NOT NULL,
  image_url       VARCHAR2(500 CHAR) NOT NULL,
  sort_order      NUMBER(10)       NOT NULL,
  CONSTRAINT pk_place_images            PRIMARY KEY (place_image_id),
  CONSTRAINT uk_place_images_order      UNIQUE (place_id, sort_order),
  CONSTRAINT ck_place_images_sort_order CHECK (sort_order >= 1)
);

-- 13. station_favorites : 역 즐겨찾기
CREATE TABLE station_favorites (
  favorite_id  NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY,
  user_id      NUMBER(19)   NOT NULL,
  station_id   NUMBER(19)   NOT NULL,
  created_at   TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_station_favorites      PRIMARY KEY (favorite_id),
  CONSTRAINT uk_favorites_user_station UNIQUE (user_id, station_id)
);

-- 14. travel_plans : 여행 동선 계획
CREATE TABLE travel_plans (
  plan_id           NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
  user_id           NUMBER(19)       NOT NULL,
  plan_title        VARCHAR2(100 CHAR) NOT NULL,
  start_station_id  NUMBER(19)       NOT NULL,
  end_station_id    NUMBER(19)       NOT NULL,
  created_at        TIMESTAMP(0)     DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at        TIMESTAMP(0)     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_travel_plans PRIMARY KEY (plan_id)
);

-- 15. travel_plan_items : 여행 계획 상세
CREATE TABLE travel_plan_items (
  plan_item_id  NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
  plan_id       NUMBER(19)       NOT NULL,
  place_id      NUMBER(19)       NOT NULL,
  station_id    NUMBER(19),
  visit_time    VARCHAR2(8 CHAR) NOT NULL,
  memo          VARCHAR2(255 CHAR),
  CONSTRAINT pk_travel_plan_items       PRIMARY KEY (plan_item_id),
  CONSTRAINT ck_tpi_visit_time_format   CHECK (REGEXP_LIKE(visit_time, '^[0-9]{2}:[0-9]{2}:[0-9]{2}$'))
);

-- 16. reviews : 여행 후기
CREATE TABLE reviews (
  review_id         NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
  user_id           NUMBER(19)       NOT NULL,
  title             VARCHAR2(100 CHAR) NOT NULL,
  content           CLOB             NOT NULL,
  start_station_id  NUMBER(19)       NOT NULL,
  end_station_id    NUMBER(19)       NOT NULL,
  rating            NUMBER(3)        NOT NULL,
  travel_cost       NUMBER(10),
  plan_id           NUMBER(19),
  view_count        NUMBER(10)       DEFAULT 0 NOT NULL,
  created_at        TIMESTAMP(0)     DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at        TIMESTAMP(0)     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_reviews             PRIMARY KEY (review_id),
  CONSTRAINT ck_reviews_rating      CHECK (rating BETWEEN 1 AND 10),
  CONSTRAINT ck_reviews_travel_cost CHECK (travel_cost >= 0),
  CONSTRAINT ck_reviews_view_count  CHECK (view_count >= 0)
);

-- 17. review_media : 후기 첨부 미디어
CREATE TABLE review_media (
  media_id    NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
  review_id   NUMBER(19)       NOT NULL,
  media_url   VARCHAR2(500 CHAR) NOT NULL,
  media_type  VARCHAR2(10 CHAR)  NOT NULL,
  CONSTRAINT pk_review_media            PRIMARY KEY (media_id),
  CONSTRAINT ck_review_media_media_type CHECK (media_type IN ('IMAGE', 'VIDEO'))
);

-- 18. review_tags : 후기 태그
CREATE TABLE review_tags (
  review_tag_id  NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
  review_id      NUMBER(19)      NOT NULL,
  tag_name       VARCHAR2(30 CHAR) NOT NULL,
  CONSTRAINT pk_review_tags PRIMARY KEY (review_tag_id),
  CONSTRAINT uk_review_tags UNIQUE (review_id, tag_name)
);

-- 19. notices : 공지사항
CREATE TABLE notices (
  notice_id    NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
  admin_id     NUMBER(19),
  title        VARCHAR2(200 CHAR) NOT NULL,
  content      CLOB             NOT NULL,
  notice_type  VARCHAR2(20 CHAR)  DEFAULT 'BOARD' NOT NULL,
  created_at   TIMESTAMP(0)     DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at   TIMESTAMP(0)     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_notices             PRIMARY KEY (notice_id),
  CONSTRAINT ck_notices_notice_type CHECK (notice_type IN ('ALARM', 'BOARD'))
);

-- 20. line_view_logs : 노선 조회 로그
CREATE TABLE line_view_logs (
  log_id     NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY,
  line_id    NUMBER(19)   NOT NULL,
  user_id    NUMBER(19),
  viewed_at  TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_line_view_logs PRIMARY KEY (log_id)
);

-- 21. board_posts : 인원 모집 게시글
CREATE TABLE board_posts (
  post_id           NUMBER(19)       GENERATED BY DEFAULT AS IDENTITY,
  user_id           NUMBER(19)       NOT NULL,
  title             VARCHAR2(100 CHAR) NOT NULL,
  content           CLOB             NOT NULL,
  view_count        NUMBER(10)       DEFAULT 0 NOT NULL,
  recruit_capacity  NUMBER(10)       NOT NULL,
  recruit_deadline  DATE             NOT NULL,
  recruit_status    VARCHAR2(20 CHAR)  DEFAULT 'RECRUITING' NOT NULL,
  meeting_date      DATE,
  plan_id           NUMBER(19),
  created_at        TIMESTAMP(0)     DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at        TIMESTAMP(0)     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_board_posts                  PRIMARY KEY (post_id),
  CONSTRAINT ck_board_posts_view_count       CHECK (view_count >= 0),
  CONSTRAINT ck_board_posts_recruit_capacity CHECK (recruit_capacity >= 1),
  CONSTRAINT ck_board_posts_recruit_status   CHECK (recruit_status IN ('RECRUITING', 'CLOSED'))
);

-- 22. post_participants : 모집 참여자
CREATE TABLE post_participants (
  participant_id  NUMBER(19)      GENERATED BY DEFAULT AS IDENTITY,
  post_id         NUMBER(19)      NOT NULL,
  user_id         NUMBER(19)      NOT NULL,
  status          VARCHAR2(20 CHAR) DEFAULT 'APPLIED' NOT NULL,
  applied_at      TIMESTAMP(0)    DEFAULT SYSTIMESTAMP NOT NULL,
  responded_at    TIMESTAMP(0),
  CONSTRAINT pk_post_participants     PRIMARY KEY (participant_id),
  CONSTRAINT uk_post_participants     UNIQUE (post_id, user_id),
  CONSTRAINT ck_post_participants_status CHECK (status IN ('APPLIED', 'ACCEPTED', 'REJECTED', 'CANCELED'))
);


-- 23. travel_plan_share_links : 여행 계획 공유 링크
CREATE TABLE travel_plan_share_links (
  share_link_id  NUMBER(19)        GENERATED BY DEFAULT AS IDENTITY,
  plan_id        NUMBER(19)        NOT NULL,
  token_hash     VARCHAR2(64 CHAR) NOT NULL,
  created_at     TIMESTAMP(0)      DEFAULT SYSTIMESTAMP NOT NULL,
  expires_at     TIMESTAMP(0)      NOT NULL,
  revoked_at     TIMESTAMP(0),
  CONSTRAINT pk_travel_plan_share_links            PRIMARY KEY (share_link_id),
  CONSTRAINT uk_travel_plan_share_links_token_hash UNIQUE (token_hash),
  CONSTRAINT ck_travel_plan_share_links_expires_at CHECK (expires_at > created_at),
  CONSTRAINT ck_travel_plan_share_links_revoked_at CHECK (revoked_at IS NULL OR revoked_at >= created_at)
);

