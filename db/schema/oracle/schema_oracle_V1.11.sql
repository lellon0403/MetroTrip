-- =====================================================================
-- 지하철 노선 기반 관광 추천 서비스 (MetroTrip)
-- Oracle 백업용 스키마
--
-- 근거 문서 : 데이터베이스 명세서 V1.11
-- 원본 스키마 : schema_mysql_V1.11.sql (MySQL 8.0)
-- 대상 DBMS : Oracle 12.2 이상
--   ※ 제약 이름이 30자를 넘는 것이 6건 있어 11g 이하에서는 실행되지 않는다.
--      원본과의 대조를 위해 이름을 그대로 유지했다.
--
-- 구성 : 23개 테이블 / 146컬럼 / PK 23 / UNIQUE 11 / FK 35 / CHECK 22 / 인덱스 3
--        (+ TIME 형식 검증 CHECK 3건 추가 — 아래 타입 매핑 참조)
--
-- 목적 : MySQL 운영 DB 의 데이터를 Oracle 로 옮겨 보관한다.
--        구조를 1:1로 맞춰 두어 원본과 대조·복구가 가능하도록 한다.
-- =====================================================================


-- =====================================================================
-- 타입·문법 매핑 (MySQL → Oracle)
-- =====================================================================
--
--  MySQL                          Oracle                    비고
--  ------------------------------------------------------------------
--  BIGINT AUTO_INCREMENT          NUMBER(19) IDENTITY       GENERATED BY DEFAULT.
--                                                           적재 후 순번 재설정 필요(STEP 3)
--  BIGINT                         NUMBER(19)
--  INT                            NUMBER(10)
--  TINYINT                        NUMBER(3)
--  TINYINT(1)                     NUMBER(1)
--  DECIMAL(10,7)                  NUMBER(10,7)
--  VARCHAR(n)                     VARCHAR2(n CHAR)          CHAR 단위 명시. 한글 1자 = 1
--  TEXT                           CLOB
--  DATETIME                       TIMESTAMP(0)
--  DATE                           DATE                      Oracle DATE 는 시분초 포함
--  TIME                           VARCHAR2(8 CHAR)          아래 설명 참조
--
-- TIME 타입이 없는 문제
--   Oracle 에는 시각만 담는 타입이 없다. 후보는 두 가지였다.
--     (1) VARCHAR2(8)              — 원본 문자열을 그대로 보존. 채택
--     (2) INTERVAL DAY TO SECOND   — 의미상 정확하나 적재 시 변환이 필요
--   백업이 목적이므로 무손실 왕복을 우선해 (1)을 선택했다.
--   HH24:MI:SS 로 0 채움 형식이면 문자열 정렬 결과가 시각 순서와 일치한다.
--   24:00 이후 값(원본에 24:01:00 등이 존재)도 그대로 보존된다.
--   형식이 깨지는 것을 막기 위해 CHECK 제약을 함께 건다.
--
-- 그대로 옮기지 않은 것
--   ON UPDATE CURRENT_TIMESTAMP  Oracle 에 대응 문법이 없다. 트리거로 구현할 수 있으나
--                                백업본에서는 원본 값을 덮어쓰면 안 되므로 넣지 않는다.
--   ON DELETE RESTRICT           Oracle 은 이 구문을 지원하지 않는다. 절을 생략하면
--                                기본 동작이 NO ACTION 이라 결과가 동일하다. (12건)
--   ENGINE / CHARSET             Oracle 에 해당 개념이 없어 제거.
--                                DB 캐릭터셋이 AL32UTF8 인지 먼저 확인할 것.
--   COMMENT 인라인               Oracle 은 COMMENT ON 문으로 분리한다. 파일 하단 참조.
-- =====================================================================


